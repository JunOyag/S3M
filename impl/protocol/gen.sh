#!/usr/bin/env bash
# Régénère impl/protocol/src/generated/ depuis schemas/**/*.fbs avec flatc
# (paquet Debian flatbuffers-compiler 23.5.26, même version que la crate
# `flatbuffers` de Cargo.toml). Le code généré est versionné : ce script
# n'est lancé qu'après une modification de schéma.
# Usage, depuis la racine du dépôt :  bash impl/protocol/gen.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && (pwd -W 2>/dev/null || pwd))"
MSYS_NO_PATHCONV=1 docker run --rm -v "$root:/w" -w /w/schemas debian:trixie-slim bash -c "
  set -e
  apt-get update -qq >/dev/null && apt-get install -y -qq flatbuffers-compiler >/dev/null 2>&1
  test \"\$(flatc --version)\" = 'flatc version 23.5.26'
  rm -rf /w/impl/protocol/src/generated
  flatc --rust -o /w/impl/protocol/src/generated --rust-module-root-file \$(find . -name '*.fbs' | sort)
"
# flatc réécrit mod.rs à chaque fichier d'entrée : on le reconstruit depuis
# l'arborescence générée (un module par espace de noms).
gen="$(dirname "$0")/src/generated"
{
  echo "// Automatically generated by impl/protocol/gen.sh. Do not modify."
  echo "// @generated"
  echo "pub mod s3m {"
  echo "  use super::*;"
  for ns in $(ls "$gen/s3m" | sort); do
    echo "  pub mod $ns {"
    echo "    use super::*;"
    for f in $(ls "$gen/s3m/$ns" | sort); do
      m="${f%.rs}"
      echo "    mod $m;"
      echo "    pub use self::$m::*;"
    done
    echo "  } // $ns"
  done
  echo "} // s3m"
} > "$gen/mod.rs"
echo "généré : impl/protocol/src/generated/"
